#!/usr/bin/env python3
"""Run full-network integer C-sim parity for frozen four-stage candidates.

This gate consumes the real-checkpoint, training-only activation-calibrated
Python INT8 reference generated by ``run_fourstage_int8_reference_gate.py`` and
builds one Vitis HLS C-simulation harness per deployment candidate.

The generated C++ is deliberately a C-sim parity harness, not the synthesizable
full-network datapath.  Passing this script means only:

* the same quantized weights, activation scales, rounding, saturation and
  residual semantics reproduce the Python INT8 reference logits exactly; and
* C-sim ran successfully for the preregistered representative checkpoints.

It does not claim RTL co-sim, complete-network HLS synthesis, place-and-route,
bitstream generation, COM5 board execution, or measured power.
"""

