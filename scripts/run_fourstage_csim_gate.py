@dataclass(frozen=True)
class TensorShape:
    channels: int
    height: int
    width: int

    @property
    def size(self) -> int:
        return int(self.channels * self.height * self.width)


@dataclass(frozen=True)
class ConvLayerSpec:
    identifier: str
    input_shape: TensorShape
    output_shape: TensorShape
    kernel_h: int
    kernel_w: int
    stride: int
    pad_h: int
    pad_w: int
    groups: int
    weights: list[int]
    bias: list[int]
    multiplier_numerator: int
    multiplier_denominator: int
    activation: str
    activation_upper: int


@dataclass(frozen=True)
class LinearLayerSpec:
    identifier: str
    in_features: int
    out_features: int
    weights: list[int]
    bias: list[int]
    multiplier_numerator: int
    multiplier_denominator: int


class CppNetworkEmitter:
    """Emit candidate-specific C++ that mirrors the Python INT8 reference."""

    def __init__(self, model: torch.nn.Module, calibration: dict[str, Any]):
        validate_reference_supported_model(model)
        self.model = model.eval()
        self.scales = {
            str(key): float(value) for key, value in calibration["scales"].items()
        }
        self.conv_layers: list[ConvLayerSpec] = []
        self.linear_layers: list[LinearLayerSpec] = []
        self.ops: list[str] = []
        self.current_shape = TensorShape(1, 224, 224)
        self.current_scale = float(self.scales["input"])

    @staticmethod
    def _identifier(name: str) -> str:
        cleaned = "".join(ch if ch.isalnum() else "_" for ch in name)
        while "__" in cleaned:
            cleaned = cleaned.replace("__", "_")
        return cleaned.strip("_")

    @staticmethod
    def _same_scale(left: float, right: float) -> bool:
        return math.isclose(float(left), float(right), rel_tol=0.0, abs_tol=1e-15)

    @staticmethod
    def _relu6_upper(output_scale: float) -> int:
        return min(127, max(0, int(round(6.0 / float(output_scale)))))

    def _scale_ratio(self, input_scale: float, weight_scale: float, output_scale: float) -> tuple[int, int]:
        return scale_to_multiplier(float(input_scale) * float(weight_scale) / float(output_scale))

    def _rescale_ratio(self, input_scale: float, output_scale: float) -> tuple[int, int] | None:
        if self._same_scale(input_scale, output_scale):
            return None
        return scale_to_multiplier(float(input_scale) / float(output_scale))

    def add_conv(
        self,
        *,
        name: str,
        conv: torch.nn.Conv2d,
        bn: torch.nn.BatchNorm2d,
        output_scale: float,
        activation: str | None,
    ) -> None:
        qconv = _quantized_conv(conv, bn, input_scale=float(self.current_scale))
        stride_h, stride_w = tuple(int(value) for value in conv.stride)
        pad_h, pad_w = tuple(int(value) for value in conv.padding)
        if stride_h != stride_w:
            raise ValueError(f"{name}: only equal H/W stride is supported")
        in_c, in_h, in_w = (
            int(conv.in_channels),
            int(self.current_shape.height),
            int(self.current_shape.width),
        )
        kernel_h, kernel_w = tuple(int(value) for value in conv.kernel_size)
        out_h = (in_h + 2 * pad_h - kernel_h) // stride_h + 1
        out_w = (in_w + 2 * pad_w - kernel_w) // stride_w + 1
        output_shape = TensorShape(int(conv.out_channels), out_h, out_w)
        numerator, denominator = self._scale_ratio(
            self.current_scale,
            qconv.weight_scale,
            float(output_scale),
        )
        identifier = self._identifier(name)
        layer = ConvLayerSpec(
            identifier=identifier,
            input_shape=TensorShape(in_c, in_h, in_w),
            output_shape=output_shape,
            kernel_h=kernel_h,
            kernel_w=kernel_w,
            stride=stride_h,
            pad_h=pad_h,
            pad_w=pad_w,
            groups=int(conv.groups),
            weights=[int(value) for value in qconv.weight.reshape(-1).tolist()],
            bias=[int(value) for value in qconv.bias.reshape(-1).tolist()],
            multiplier_numerator=int(numerator),
            multiplier_denominator=int(denominator),
            activation=activation or "none",
            activation_upper=(
                self._relu6_upper(output_scale) if activation == "relu6" else 127
            ),
        )
        self.conv_layers.append(layer)
        self.ops.append(f"  conv2d_layer(x, y, L_{identifier});")
        self.ops.append("  x.swap(y);")
        self.current_shape = output_shape
        self.current_scale = float(output_scale)

    def add_residual(self, *, input_scale: float, output_scale: float) -> None:
        ratio = self._rescale_ratio(input_scale, output_scale)
        self.ops.append("    std::vector<i8> identity;")
        if ratio is None:
            self.ops.append("    identity = residual;")
        else:
            numerator, denominator = ratio
            self.ops.append(
                f"    rescale_tensor(residual, identity, {int(numerator)}LL, {int(denominator)}LL);"
            )
        self.ops.append("    residual_add_tensor(x, identity, y);")
        self.ops.append("    x.swap(y);")
        self.current_scale = float(output_scale)

    def add_linear(self, *, name: str, linear: torch.nn.Linear, output_scale: float) -> None:
        qlinear = _quantized_linear(linear, input_scale=float(self.current_scale))
        numerator, denominator = self._scale_ratio(
            self.current_scale,
            qlinear.weight_scale,
            float(output_scale),
        )
        identifier = self._identifier(name)
        layer = LinearLayerSpec(
            identifier=identifier,
            in_features=int(linear.in_features),
            out_features=int(linear.out_features),
            weights=[int(value) for value in qlinear.weight.reshape(-1).tolist()],
            bias=(
                [0 for _ in range(int(linear.out_features))]
                if qlinear.bias is None
                else [int(value) for value in qlinear.bias.reshape(-1).tolist()]
            ),
            multiplier_numerator=int(numerator),
            multiplier_denominator=int(denominator),
        )
        self.linear_layers.append(layer)
        self.ops.append(f"  linear_layer(x, y, L_{identifier});")
        self.ops.append("  x.swap(y);")
        self.current_shape = TensorShape(int(linear.out_features), 1, 1)
        self.current_scale = float(output_scale)

    def add_gap(self, *, output_scale: float) -> None:
        shape = self.current_shape
        self.ops.append(
            f"  avg_pool_global(x, y, {shape.channels}, {shape.height}, {shape.width});"
        )
        self.ops.append("  x.swap(y);")
        ratio = self._rescale_ratio(self.current_scale, output_scale)
        if ratio is not None:
            numerator, denominator = ratio
            self.ops.append(
                f"  rescale_tensor(x, y, {int(numerator)}LL, {int(denominator)}LL);"
            )
            self.ops.append("  x.swap(y);")
        self.current_shape = TensorShape(shape.channels, 1, 1)
        self.current_scale = float(output_scale)

    def emit_model_ops(self) -> None:
        stem_block = self.model.stem.conv
        if not isinstance(stem_block, ConvBlock):
            raise ValueError("four-stage stem must contain ConvBlock stem.conv")
        self.add_conv(
            name="stem_conv",
            conv=stem_block.conv,
            bn=stem_block.bn,
            output_scale=float(self.scales["stem.conv"]),
            activation="relu",
        )

        for stage_index, stage in enumerate(self.model.stages):
            for block_index, block in enumerate(stage):
                name = f"stages.{stage_index}.{block_index}"
                if isinstance(block, ConvBlock):
                    self.add_conv(
                        name=name,
                        conv=block.conv,
                        bn=block.bn,
                        output_scale=float(self.scales[name]),
                        activation="relu",
                    )
                elif isinstance(block, MBConvBlock):
                    residual_scale = float(self.current_scale)
                    if block.use_residual:
                        self.ops.append("  {")
                        self.ops.append("    std::vector<i8> residual = x;")
                    if block.use_expand:
                        self.add_conv(
                            name=f"{name}.expand",
                            conv=block.expand_conv,
                            bn=block.expand_bn,
                            output_scale=float(self.scales[f"{name}.expand_relu"]),
                            activation="relu6",
                        )
                    self.add_conv(
                        name=f"{name}.dw",
                        conv=block.dw_conv,
                        bn=block.dw_bn,
                        output_scale=float(self.scales[f"{name}.dw_relu"]),
                        activation="relu6",
                    )
                    self.add_conv(
                        name=f"{name}.project",
                        conv=block.project_conv,
                        bn=block.project_bn,
                        output_scale=float(self.scales[name]),
                        activation=None,
                    )
                    if block.use_residual:
                        self.add_residual(
                            input_scale=residual_scale,
                            output_scale=float(self.scales[name]),
                        )
                        self.ops.append("  }")
                elif isinstance(block, SkipBlock):
                    if not block.use_conv:
                        continue
                    self.add_conv(
                        name=name,
                        conv=block.conv,
                        bn=block.bn,
                        output_scale=float(self.scales[name]),
                        activation=None,
                    )
                else:  # pragma: no cover - validate_reference_supported_model catches this.
                    raise ValueError(f"unsupported block: {block.__class__.__name__}")

        self.add_gap(output_scale=float(self.scales["head.gap"]))
        self.add_linear(
            name="head.fc",
            linear=self.model.head.fc,
            output_scale=float(self.scales["head.fc"]),
        )

    @staticmethod
    def _array_initializer(values: list[int], *, per_line: int = 24) -> str:
        chunks = []
        for offset in range(0, len(values), per_line):
            chunk = ", ".join(str(int(value)) for value in values[offset : offset + per_line])
            chunks.append(f"  {chunk}")
        return ",\n".join(chunks)

    def _emit_layer_arrays(self) -> str:
        pieces: list[str] = []
        for layer in self.conv_layers:
            pieces.append(
                f"static const i8 W_{layer.identifier}[{len(layer.weights)}] = {{\n"
                f"{self._array_initializer(layer.weights)}\n}};\n"
            )
            pieces.append(
                f"static const i32 B_{layer.identifier}[{len(layer.bias)}] = {{\n"
                f"{self._array_initializer(layer.bias)}\n}};\n"
            )
        for layer in self.linear_layers:
            pieces.append(
                f"static const i8 W_{layer.identifier}[{len(layer.weights)}] = {{\n"
                f"{self._array_initializer(layer.weights)}\n}};\n"
            )
            pieces.append(
                f"static const i32 B_{layer.identifier}[{len(layer.bias)}] = {{\n"
                f"{self._array_initializer(layer.bias)}\n}};\n"
            )
        return "\n".join(pieces)

    def _emit_layer_structs(self) -> str:
        pieces: list[str] = []
        for layer in self.conv_layers:
            activation_code = {"none": 0, "relu": 1, "relu6": 2}[layer.activation]
            pieces.append(
                dedent(
                    f"""
                    static const ConvLayer L_{layer.identifier} = {{
                      {layer.input_shape.channels}, {layer.input_shape.height}, {layer.input_shape.width},
                      {layer.output_shape.channels}, {layer.output_shape.height}, {layer.output_shape.width},
                      {layer.kernel_h}, {layer.kernel_w}, {layer.stride}, {layer.pad_h}, {layer.pad_w},
                      {layer.groups},
                      W_{layer.identifier}, B_{layer.identifier},
                      {layer.multiplier_numerator}LL, {layer.multiplier_denominator}LL,
                      {activation_code}, {layer.activation_upper}
                    }};
                    """
                ).strip()
            )
        for layer in self.linear_layers:
            pieces.append(
                dedent(
                    f"""
                    static const LinearLayer L_{layer.identifier} = {{
                      {layer.in_features}, {layer.out_features},
                      W_{layer.identifier}, B_{layer.identifier},
                      {layer.multiplier_numerator}LL, {layer.multiplier_denominator}LL
                    }};
                    """
                ).strip()
            )
        return "\n\n".join(pieces)

    def top_cpp(self) -> str:
        if not self.ops:
            self.emit_model_ops()
        arrays = self._emit_layer_arrays()
        structs = self._emit_layer_structs()
        ops = "\n".join(self.ops)
        return dedent(
            f"""
            #include <algorithm>
            #include <climits>
            #include <cstdint>
            #include <vector>

            using i8 = signed char;
            using i32 = int;
            using i64 = long long;

            struct ConvLayer {{
              int in_c;
              int in_h;
              int in_w;
              int out_c;
              int out_h;
              int out_w;
              int kernel_h;
              int kernel_w;
              int stride;
              int pad_h;
              int pad_w;
              int groups;
              const i8* weights;
              const i32* bias;
              i64 multiplier_numerator;
              i64 multiplier_denominator;
              int activation;  // 0 none, 1 ReLU, 2 ReLU6
              int activation_upper;
            }};

            struct LinearLayer {{
              int in_features;
              int out_features;
              const i8* weights;
              const i32* bias;
              i64 multiplier_numerator;
              i64 multiplier_denominator;
            }};

            static i64 clamp_i32(i64 value) {{
              if (value < static_cast<i64>(INT32_MIN)) return static_cast<i64>(INT32_MIN);
              if (value > static_cast<i64>(INT32_MAX)) return static_cast<i64>(INT32_MAX);
              return value;
            }}

            static i8 clamp_i8_symmetric(i64 value) {{
              if (value < -127) return static_cast<i8>(-127);
              if (value > 127) return static_cast<i8>(127);
              return static_cast<i8>(value);
            }}

            static i64 round_divide_nearest_even(i64 numerator, i64 denominator) {{
              if (denominator <= 0) return 0;
              const int sign = numerator < 0 ? -1 : 1;
              unsigned long long absolute = numerator < 0
                ? static_cast<unsigned long long>(-numerator)
                : static_cast<unsigned long long>(numerator);
              const unsigned long long divisor = static_cast<unsigned long long>(denominator);
              unsigned long long quotient = absolute / divisor;
              const unsigned long long remainder = absolute % divisor;
              const unsigned long long twice = remainder * 2ULL;
              const bool increment =
                (twice > divisor) || ((twice == divisor) && ((quotient & 1ULL) == 1ULL));
              if (increment) {{
                quotient += 1ULL;
              }}
              const i64 rounded = static_cast<i64>(quotient);
              return sign < 0 ? -rounded : rounded;
            }}

            static i8 requantize_i8(i64 accumulator, i64 numerator, i64 denominator) {{
              const i64 scaled = round_divide_nearest_even(accumulator * numerator, denominator);
              return clamp_i8_symmetric(scaled);
            }}

            static i8 apply_activation(i8 value, int activation, int activation_upper) {{
              int v = static_cast<int>(value);
              if (activation == 1) {{
                if (v < 0) v = 0;
              }} else if (activation == 2) {{
                if (v < 0) v = 0;
                if (v > activation_upper) v = activation_upper;
              }}
              return static_cast<i8>(v);
            }}

            static int index3(int c, int h, int w, int height, int width) {{
              return (c * height + h) * width + w;
            }}

            static void conv2d_layer(
                const std::vector<i8>& input,
                std::vector<i8>& output,
                const ConvLayer& layer) {{
              output.assign(layer.out_c * layer.out_h * layer.out_w, static_cast<i8>(0));
              const int output_per_group = layer.out_c / layer.groups;
              const int channels_per_group = layer.in_c / layer.groups;
              for (int oc = 0; oc < layer.out_c; ++oc) {{
                const int group = oc / output_per_group;
                const int in_start = group * channels_per_group;
                for (int oh = 0; oh < layer.out_h; ++oh) {{
                  for (int ow = 0; ow < layer.out_w; ++ow) {{
                    i64 acc = static_cast<i64>(layer.bias[oc]);
                    for (int ic_local = 0; ic_local < channels_per_group; ++ic_local) {{
                      const int ic = in_start + ic_local;
                      for (int kh = 0; kh < layer.kernel_h; ++kh) {{
                        const int ih = oh * layer.stride + kh - layer.pad_h;
                        if (ih < 0 || ih >= layer.in_h) continue;
                        for (int kw = 0; kw < layer.kernel_w; ++kw) {{
                          const int iw = ow * layer.stride + kw - layer.pad_w;
                          if (iw < 0 || iw >= layer.in_w) continue;
                          const int input_index = index3(ic, ih, iw, layer.in_h, layer.in_w);
                          const int weight_index =
                            ((oc * channels_per_group + ic_local) * layer.kernel_h + kh)
                              * layer.kernel_w + kw;
                          acc += static_cast<i64>(input[input_index])
                            * static_cast<i64>(layer.weights[weight_index]);
                        }}
                      }}
                    }}
                    acc = clamp_i32(acc);
                    i8 value = requantize_i8(
                      acc, layer.multiplier_numerator, layer.multiplier_denominator);
                    value = apply_activation(value, layer.activation, layer.activation_upper);
                    output[index3(oc, oh, ow, layer.out_h, layer.out_w)] = value;
                  }}
                }}
              }}
            }}

            static void rescale_tensor(
                const std::vector<i8>& input,
                std::vector<i8>& output,
                i64 numerator,
                i64 denominator) {{
              output.resize(input.size());
              for (size_t index = 0; index < input.size(); ++index) {{
                output[index] = requantize_i8(
                  static_cast<i64>(input[index]), numerator, denominator);
              }}
            }}

            static void residual_add_tensor(
                const std::vector<i8>& left,
                const std::vector<i8>& right,
                std::vector<i8>& output) {{
              output.resize(left.size());
              for (size_t index = 0; index < left.size(); ++index) {{
                const i64 value =
                  static_cast<i64>(left[index]) + static_cast<i64>(right[index]);
                output[index] = clamp_i8_symmetric(value);
              }}
            }}

            static void avg_pool_global(
                const std::vector<i8>& input,
                std::vector<i8>& output,
                int channels,
                int height,
                int width) {{
              output.assign(channels, static_cast<i8>(0));
              const i64 denominator = static_cast<i64>(height) * static_cast<i64>(width);
              for (int c = 0; c < channels; ++c) {{
                i64 sum = 0;
                for (int h = 0; h < height; ++h) {{
                  for (int w = 0; w < width; ++w) {{
                    sum += static_cast<i64>(input[index3(c, h, w, height, width)]);
                  }}
                }}
                output[c] = clamp_i8_symmetric(round_divide_nearest_even(sum, denominator));
              }}
            }}

            static void linear_layer(
                const std::vector<i8>& input,
                std::vector<i8>& output,
                const LinearLayer& layer) {{
              output.assign(layer.out_features, static_cast<i8>(0));
              for (int out = 0; out < layer.out_features; ++out) {{
                i64 acc = static_cast<i64>(layer.bias[out]);
                for (int in = 0; in < layer.in_features; ++in) {{
                  const int weight_index = out * layer.in_features + in;
                  acc += static_cast<i64>(input[in])
                    * static_cast<i64>(layer.weights[weight_index]);
                }}
                acc = clamp_i32(acc);
                output[out] = requantize_i8(
                  acc, layer.multiplier_numerator, layer.multiplier_denominator);
              }}
            }}

            {arrays}

            {structs}

            extern "C" void fourstage_top(const i8 input[{INPUT_SIZE}], i8 output[{OUTPUT_CLASSES}]) {{
              std::vector<i8> x(input, input + {INPUT_SIZE});
              std::vector<i8> y;
            {ops}
              for (int index = 0; index < {OUTPUT_CLASSES}; ++index) {{
                output[index] = x[index];
              }}
            }}
            """
        ).lstrip()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--int8-reference-summary", default=str(DEFAULT_INT8_SUMMARY))
    parser.add_argument("--output-root", default=str(DEFAULT_OUTPUT_ROOT))
    parser.add_argument("--summary", default=str(DEFAULT_SUMMARY))
    parser.add_argument("--vitis-hls", default=str(DEFAULT_VITIS_HLS))
    parser.add_argument(
        "--run-vitis",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Run Vitis HLS csim_design after generating the C++ harness.",
    )
    parser.add_argument(
        "--candidate-limit",
        type=int,
        default=None,
        help="Debug-only candidate limit; omitted for the formal gate.",
    )
    return parser.parse_args()


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def evidence(path: Path) -> dict[str, Any]:
    return {
        "path": str(path.resolve()),
        "sha256": sha256_file(path),
        "size_bytes": path.stat().st_size,
    }


def maybe_evidence(path: Path) -> dict[str, Any] | None:
    return evidence(path) if path.is_file() else None


def git_output(*args: str) -> str:
    completed = subprocess.run(
        ["git", *args],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip()


def safe_name(text: str) -> str:
    return "".join(ch if ch.isalnum() or ch in {"-", "_"} else "_" for ch in text)


def cpp_string(path: Path) -> str:
    return str(path.resolve()).replace("\\", "/")


